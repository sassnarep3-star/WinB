// consolidate.mjs — final-integration step.
//
// main accumulated six competing site generations from parallel sessions:
//   /            (v1 "Counterwise" then v6 "Crisp Kitchen")  <- canonical
//   /docs/       (v2)
//   /alt-site/build/ (v3)
//   /legacy-docs-site/ (v4)
//   three root folders with the same purpose: products/ verification/ compliance/
//   three build systems: tools/build.js, scripts/build.py, alt-site/build/build.py
//
// The brief asks for one site to index. This retires the others without deleting
// anyone's work: every superseded page gets a noindex meta tag and a small,
// visible banner pointing at the equivalent page on the canonical site. Files
// stay in the repository; they simply stop competing in search.
//
// It also fixes the compliance defect described in FLG-010: the /go/ redirect
// pages marked themselves noindex,nofollow while exposing an affiliate link,
// which is precisely the sneaky-redirect pattern Google's spam policy names.

import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SITE = 'https://sassnarep3-star.github.io/WinB';

// Superseded trees, and where a reader should go instead.
const RETIRED = [
  { dir: 'docs', to: '/', why: 'an earlier generation of this site' },
  { dir: 'legacy-docs-site', to: '/', why: 'an earlier generation, kept for the record' },
  { dir: 'alt-site/build', to: '/', why: 'a parallel session’s build output' },
  { dir: 'alt-site', to: '/', why: 'a parallel session’s source; documented in the archive' },
  { dir: 'products', to: '/reviews/', why: 'folded into the product pages' },
  { dir: 'verification', to: '/data-room/', why: 'folded into the Data Room' },
  { dir: 'compliance', to: '/methods/', why: 'folded into How this site works' },
  { dir: 'platform', to: '/decisions/', why: 'folded into the Decision Room' },
  { dir: 'archive', to: '/', why: 'superseded snapshots' },
];

const touched = [];
const goFixed = [];

function walk(dir, out = []) {
  for (const n of readdirSync(dir)) {
    const f = join(dir, n);
    if (statSync(f).isDirectory()) walk(f, out);
    else out.push(f);
  }
  return out;
}

const banner = (to, why) => `<div id="archive-notice" style="position:relative;z-index:9999;background:#191714;color:#fbf8f3;font:14px/1.5 ui-sans-serif,system-ui,sans-serif;padding:12px 18px;text-align:center">
  <strong>Archived page.</strong> This is ${why}, kept for the record and excluded from search.
  The current site is <a href="${SITE}/" style="color:#f0b48a">Counterwise</a>${to !== '/' ? ` — a matching page is at <a href="${SITE}${to}" style="color:#f0b48a">${to}</a>` : ''}.
</div>`;

// -------------------------------------------------- 1. retire superseded HTML
for (const { dir, to, why } of RETIRED) {
  const abs = join(ROOT, dir);
  if (!existsSync(abs)) continue;
  for (const file of walk(abs)) {
    if (!file.endsWith('.html')) continue;
    let html = readFileSync(file, 'utf8');
    if (html.includes('id="archive-notice"')) continue;

    // Force noindex, replacing any existing robots meta.
    if (/<meta name="robots"[^>]*>/i.test(html)) {
      html = html.replace(/<meta name="robots"[^>]*>/i, '<meta name="robots" content="noindex,nofollow">');
    } else if (/<head[^>]*>/i.test(html)) {
      html = html.replace(/<head[^>]*>/i, '<head>\n<meta name="robots" content="noindex,nofollow">');
    } else {
      html = '<meta name="robots" content="noindex,nofollow">\n' + html;
    }

    // Banner directly after <body ...>.
    if (/<body[^>]*>/i.test(html)) {
      html = html.replace(/<body[^>]*>/i, (m) => `${m}\n${banner(to, why)}`);
    } else {
      html = banner(to, why) + html;
    }

    writeFileSync(file, html, 'utf8');
    touched.push(relative(ROOT, file));
  }
}

// ------------------------ 1b. retire the parallel Python build's output tree
// alt-site/build/ is regenerated by its own build.py and by the repository's
// "Alternate site check" workflow, so noindexing it in place would be undone on
// every run and would put two CI jobs in a fight. Instead, publish a robots
// rule that excludes it: the files stay (nothing 404s), the rules stay stable,
// and the site stops competing with the canonical build in search.
{
  const robotsPath = join(ROOT, 'robots.txt');
  let robots = readFileSync(robotsPath, 'utf8');
  const block = [
    '',
    '# Superseded generations from parallel sessions. Kept (links and archives',
    '# still resolve) but excluded from indexing so one site is indexable.',
    'Disallow: /WinB/docs/',
    'Disallow: /WinB/legacy-docs-site/',
    'Disallow: /WinB/alt-site/',
    'Disallow: /WinB/archive/',
    'Disallow: /WinB/products/',
    'Disallow: /WinB/verification/',
    'Disallow: /WinB/compliance/',
    'Disallow: /WinB/platform/',
    '',
  ].join('\n');
  if (!robots.includes('Disallow: /WinB/alt-site/')) {
    // Insert before the Sitemap line so the directive order stays conventional.
    robots = robots.replace(/Sitemap:/, block.trim() + '\n\nSitemap:');
    writeFileSync(robotsPath, robots, 'utf8');
    touched.push('robots.txt (archive exclusions)');
  }
}

// ---------------------------------- 2. /go/ redirect pages: fix noindex,nofollow
// A page that is noindex,nofollow but forwards to an affiliate URL is a sneaky
// redirect. These are legitimate affiliate landing pages on our own domain, so
// they should be indexed, carry the disclosure, and link out with rel=sponsored.
const goDir = join(ROOT, 'go');
if (existsSync(goDir)) {
  for (const file of walk(goDir)) {
    if (!file.endsWith('.html')) continue;
    let html = readFileSync(file, 'utf8');
    const before = html;
    html = html.replace(/<meta name="robots" content="noindex,nofollow">/i,
      '<meta name="robots" content="index,follow">');
    // Point the "back" link at the live page, not the archived Crisp Kitchen root.
    html = html.replace(/<a href="\/index\.html">← The Crisp Kitchen<\/a>/,
      `<a href="${SITE}/">← Counterwise</a>`);
    html = html.replace(/href="\/WinB\/index\.html"/g, `href="${SITE}/"`);
    if (html !== before) {
      writeFileSync(file, html, 'utf8');
      goFixed.push(relative(ROOT, file));
    }
  }
}

// -------------- 3. one identity, one indexable copy of every topic  (S18)
// Two problems were visible to a reader and to a crawler at the same time:
//   (a) eleven indexable pages carried a second brand — “The Crisp Kitchen” —
//       including the register hub the footer links to and the five /go/ exit
//       pages that forward shoppers to Amazon;
//   (b) four /guides/ URLs from the register generation were near-duplicates of
//       published Counterwise guides, both marked index,follow, so the two
//       generations competed for the same queries on one host (the doorway and
//       site-reputation patterns named in Google's spam policies), and the
//       duplicate pages were listed in sitemap-register.xml while being treated
//       as superseded by tools/verify.mjs.
// Nothing is deleted here. The duplicates stay reachable at their old URLs,
// they simply stop asking to be indexed, and their canonical points at the copy
// the publication wants to rank.
const REBRAND = [
  'register/index.html',
  'about/editorial-policy.html',
  'about/how-we-make-money.html',
  'about/privacy.html',
  'go/chef-iq-sense-gen3.html',
  'go/chefman-6-quart-dual-basket.html',
  'go/chefman-8-quart-turbofry.html',
  'go/emeril-lagasse-26qt-french-door.html',
  'go/thermomaven-1-second-thermometer.html',
];

// Pages the canonical site already answers better, with the URL that answers it.
const DUPLICATES = {
  'guides/basket-or-oven-air-fryer.html': '/guides/basket-or-oven.html',
  'guides/air-fryer-capacity-checklist.html': '/guides/capacity-checklist.html',
  'guides/cleanup-and-counter-space.html': '/guides/cleanup-counter.html',
  'guides/multifunction-appliance-questions.html': '/guides/multifunction.html',
  'about/privacy.html': '/privacy/',
  'decisions/questions.html': '/suggestions/',
  'decisions/growth-plan.html': '/data-room/',
};

const rebranded = [];
for (const rel of REBRAND) {
  const abs = join(ROOT, rel);
  if (!existsSync(abs)) continue;
  let html = readFileSync(abs, 'utf8');
  const before = html;
  html = html
    .split('The Crisp Kitchen').join('Counterwise')
    .split('>CK</span>').join('>cw</span>');
  if (html !== before) {
    writeFileSync(abs, html, 'utf8');
    rebranded.push(rel);
  }
}

const deindexed = [];
for (const [rel, to] of Object.entries(DUPLICATES)) {
  const abs = join(ROOT, rel);
  if (!existsSync(abs)) continue;
  let html = readFileSync(abs, 'utf8');
  const before = html;
  const robots = '<meta name="robots" content="noindex,follow">';
  html = /<meta name="robots"[^>]*>/i.test(html)
    ? html.replace(/<meta name="robots"[^>]*>/i, robots)
    : html.replace(/<head[^>]*>/i, (m) => `${m}\n${robots}`);
  const canonical = `<link rel="canonical" href="${SITE}${to}">`;
  html = /<link rel="canonical"[^>]*>/i.test(html)
    ? html.replace(/<link rel="canonical"[^>]*>/i, canonical)
    : html.replace(/<\/title>/i, `</title>\n${canonical}`);
  // A reader arriving from an old search result deserves to know where they are.
  if (!html.includes('data-dup-note')) {
    html = html.replace(/<main\b[^>]*>/i, (m) =>
      `${m}\n<p class="small" data-dup-note style="margin:0">This topic is answered by the current Counterwise publication — ` +
      `<a href="${to}">read it here</a>. This URL is kept so older links keep working.</p>`);
  }
  if (html !== before) {
    writeFileSync(abs, html, 'utf8');
    deindexed.push(`${rel} -> ${to}`);
  }
}

// A sitemap must not list a page that tells crawlers not to index it. Both
// sitemaps are checked against the robots meta actually on the page, so the
// register sitemap cannot keep advertising trees this file has just retired.
function noindexed(locPath) {
  const relPath = locPath.replace(/^\/WinB\/?/, '').replace(/\/$/, '/index.html');
  const abs = join(ROOT, relPath);
  if (!existsSync(abs)) return false;
  return /<meta name="robots" content="[^"]*noindex/i.test(readFileSync(abs, 'utf8'));
}
for (const name of ['sitemap-register.xml']) {
  const file = join(ROOT, name);
  if (!existsSync(file)) continue;
  const xml = readFileSync(file, 'utf8');
  let dropped = 0;
  const pruned = xml.replace(/<url>(?:(?!<\/url>)[\s\S])*?<\/url>\s*/g, (block) => {
    const loc = (block.match(/<loc>([^<]+)<\/loc>/) || [])[1] || '';
    if (loc && noindexed(loc.replace(SITE, ''))) { dropped++; return ''; }
    return block;
  });
  if (pruned !== xml) {
    writeFileSync(file, pruned, 'utf8');
    console.log(`consolidate: ${name} pruned of ${dropped} noindex URLs`);
  }
}

console.log(`consolidate: ${rebranded.length} surviving pages rebranded to the single publication identity`);
console.log(`consolidate: ${deindexed.length} duplicate URLs de-indexed with a canonical to their twin`);
for (const d of deindexed) console.log('   dup: ' + d);

console.log(`consolidate: ${touched.length} archived pages marked noindex + banner`);
console.log(`consolidate: ${goFixed.length} /go/ redirect pages changed to index,follow`);
for (const g of goFixed) console.log('   go: ' + g);
